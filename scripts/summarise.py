"""
Reads results/runs/*.jsonl + results/gold_answers.json and writes
results/summary.json and docs/RESULTS.md. Every number in RESULTS.md comes from here.

Rates are shares of answers (Gemini: all 3 repeats pooled), shown with n.
"""

import datetime as dt
import json
import random
import sys
from collections import Counter, defaultdict
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from copilot import config  # noqa: E402
from copilot.benchmark import BLIND_GOLD_FILE, load_gold, load_questions  # noqa: E402

GRADES = ("correct", "silent_error", "error_or_refusal")
SETUP_ORDER = ["s1_raw", "s1d_raw_docs", "s2_modelled", "s3_docs", "s4_semantic"]
SETUP_NAME = {"s1_raw": "1 Raw, schema only", "s1d_raw_docs": "1+ Raw + docs (extra)",
              "s2_modelled": "2 Cleaned, schema only", "s3_docs": "3 Cleaned + docs",
              "s4_semantic": "4 Cleaned + semantic layer"}


# Section 11: what the loud errors were. Fixed text patterns on the stored error and SQL,
# checked in this order. Descriptive only: no grade is changed by this.
ERROR_CAUSES = [
    ("harness crash (MetricFlow subprocess did not start; not the model's fault)",
     lambda r: "Fatal Python error" in (r["error"] or "")),
    ("refused an answerable question", lambda r: r["error_type"] == "refusal"),
    ("guard could not parse the SQL (a syntax error, not an attack)",
     lambda r: r["error_type"] == "unsafe_sql" and (r["error"] or "").startswith("cannot parse")),
    ("blocked by the guard as unsafe", lambda r: r["error_type"] == "unsafe_sql"),
    ("cleaning rule 7: reading the month out of the file name",
     lambda r: "source_file" in (r["sql"] or "").lower()),
    ("semantic layer: month written as '2023-01' instead of a full date",
     lambda r: "invalid timestamp field format" in (r["error"] or "")),
    ("semantic layer: invalid request (unknown name or key, or no metric)",
     lambda r: any(t in (r["error"] or "") for t in ("query resolution", "unknown keys", "at least one metric"))),
    ("other SQL error", lambda r: True),
]


def error_cause(r):
    return next(label for label, test in ERROR_CAUSES if test(r))


BOOT = 2000   # bootstrap resamples; seeded below so RESULTS.md is reproducible


def per_question(rows) -> dict:
    """question id -> share of its answers that are correct (Gemini's 3 repeats stay together)."""
    d = defaultdict(list)
    for r in rows:
        d[r["question_id"]].append(r["grade"] == "correct")
    return {q: sum(v) / len(v) for q, v in d.items()}


def boot_ci(values, rng) -> tuple:
    """95% percentile bootstrap interval of the mean, resampling questions."""
    n = len(values)
    means = sorted(sum(rng.choices(values, k=n)) / n for _ in range(BOOT))
    return means[int(0.025 * BOOT)], means[int(0.975 * BOOT) - 1]


def load_runs(folder: str = "runs"):
    rows = []
    for path in sorted((config.RESULTS_DIR / folder).glob("*.jsonl")):
        rows += [json.loads(line) for line in path.read_text().splitlines() if line.strip()]
    return rows


def rates(rows):
    n = len(rows)
    c = Counter(r["grade"] for r in rows)
    return {"n": n, **{g: (c[g] / n if n else None) for g in GRADES}, "counts": {g: c[g] for g in GRADES}}


def pct(x):
    return "-" if x is None else f"{100 * x:.1f}%"


def cell(r):
    return f"{pct(r['correct'])} / {pct(r['silent_error'])} / {pct(r['error_or_refusal'])} (n={r['n']})"


def table(header, body):
    out = ["| " + " | ".join(header) + " |", "|" + "|".join("---" for _ in header) + "|"]
    out += ["| " + " | ".join(str(c) for c in row) + " |" for row in body]
    return "\n".join(out)


def group(rows, key):
    d = defaultdict(list)
    for r in rows:
        d[key(r)].append(r)
    return d


def main():
    runs = load_runs()
    if not runs:
        raise SystemExit("no runs found in results/runs/")
    gold = load_gold()
    questions = {q.id: q for q in load_questions()}
    for r in runs:
        g = gold[r["question_id"]]
        r["trap"] = bool(g.get("raw_diverges"))
        r["expressible"] = bool(g.get("semantic_expressible"))
    models = sorted({r["model"] for r in runs})
    setups = [s for s in SETUP_ORDER if any(r["setup"] == s for r in runs)]
    ans = [r for r in runs if r["answerable"]]
    unans = [r for r in runs if not r["answerable"]]
    S = {"generated_at_utc": dt.datetime.now(dt.timezone.utc).isoformat(timespec="seconds"),
         "answers": {m: sum(r["model"] == m for r in runs) for m in models}}
    md = ["# Results", "",
          f"Generated by `scripts/summarise.py` on {S['generated_at_utc']} from `results/runs/*.jsonl`. "
          "Do not edit by hand.", "",
          "Each cell is **correct / silent error / error or refusal**, as a share of answers, with the "
          "number of answers (n). Answerable questions only unless stated. If a model was run more than once, its "
          "repeats are pooled.", "",
          "Answers collected: " + ", ".join(f"{m}: {S['answers'][m]:,}" for m in models), ""]

    def by_model_setup(rows, title, key=lambda r: True, label=None):
        md.append(f"## {title}\n")
        body, data = [], {}
        for s in setups:
            row = [SETUP_NAME[s]]
            for m in models:
                sub = [r for r in rows if r["setup"] == s and r["model"] == m and key(r)]
                rt = rates(sub)
                data[f"{s}|{m}"] = rt
                row.append(cell(rt) if sub else "-")
            body.append(row)
        md.append(table(["Setup"] + models, body) + "\n")
        return data

    S["headline"] = by_model_setup(ans, "1. Headline (140 answerable questions)")
    for d in (1, 2, 3):
        S[f"difficulty_{d}"] = by_model_setup(ans, f"2.{d} Difficulty level {d}", lambda r, d=d: r["difficulty"] == d)
    S["trap"] = by_model_setup(ans, "3a. Trap questions (the obvious query on raw data gives a different answer)",
                               lambda r: r["trap"])
    S["normal"] = by_model_setup(ans, "3b. Non-trap questions (raw and cleaned data agree)", lambda r: not r["trap"])

    md.append("## 4. Can documentation make up for skipping the cleaning?\n")
    md.append("Same questions, raw table, with and without docs that describe the 7 cleaning rules; "
              "cleaned table for reference. Trap questions only.\n")
    body = []
    for m in models:
        row = [m]
        for s in ("s1_raw", "s1d_raw_docs", "s2_modelled"):
            if s in setups:
                row.append(cell(rates([r for r in ans if r["model"] == m and r["setup"] == s and r["trap"]])))
        body.append(row)
    md.append(table(["Model", "Raw", "Raw + docs", "Cleaned"], body) + "\n")
    S["raw_docs_arm"] = {m: {s: rates([r for r in ans if r["model"] == m and r["setup"] == s and r["trap"]])
                             for s in ("s1_raw", "s1d_raw_docs", "s2_modelled")} for m in models}

    md.append("## 5. Why raw-data silent errors happen\n")
    md.append("Share of silent errors whose values equal the *naive raw answer* (the obvious query on the "
              "raw table), i.e. the model fell for the dirt exactly as a careless analyst would.\n")
    body, S["silent_equals_naive_raw"] = [], {}
    for s in ("s1_raw", "s1d_raw_docs"):
        if s not in setups:
            continue
        row = [SETUP_NAME[s]]
        for m in models:
            se = [r for r in ans if r["setup"] == s and r["model"] == m and r["grade"] == "silent_error"]
            k = sum(bool(r.get("matches_naive_raw")) for r in se)
            S["silent_equals_naive_raw"][f"{s}|{m}"] = {"silent_errors": len(se), "equal_naive_raw": k}
            row.append(f"{k} of {len(se)}" + (f" ({pct(k / len(se))})" if se else ""))
        body.append(row)
    md.append(table(["Setup"] + models, body) + "\n")

    md.append("## 6. Written docs vs semantic layer (same information)\n")
    md.append("Split by whether the semantic layer can express the question. For questions it cannot "
              "express, a refusal is the right behaviour for setup 4 only if the question is unanswerable; "
              "otherwise it counts as an error or refusal.\n")
    body, S["docs_vs_semantic"] = [], {}
    for label, flt in (("Expressible in the semantic layer", lambda r: r["expressible"]),
                       ("Not expressible", lambda r: not r["expressible"])):
        for m in models:
            row = [f"{label} / {m}"]
            for s in ("s3_docs", "s4_semantic"):
                rt = rates([r for r in ans if r["model"] == m and r["setup"] == s and flt(r)])
                S["docs_vs_semantic"][f"{label}|{m}|{s}"] = rt
                row.append(cell(rt) if rt["n"] else "-")
            body.append(row)
    md.append(table(["Subset / model", "Docs (setup 3)", "Semantic layer (setup 4)"], body) + "\n")
    md.append("Setup 4 on the answerable questions it cannot express: how often the model said so "
              "(a refusal; graded as an error, but the honest reply for a layer that lacks the metric) "
              "versus returning something else.\n")
    body, S["semantic_refusals_not_expressible"] = [], {}
    for m in models:
        sub = [r for r in ans if r["model"] == m and r["setup"] == "s4_semantic" and not r["expressible"]]
        k = sum(r["error_type"] == "refusal" for r in sub)
        silent = sum(r["grade"] == "silent_error" for r in sub)
        S["semantic_refusals_not_expressible"][m] = {"n": len(sub), "refused": k, "silent_error": silent}
        if sub:
            body.append([m, f"{k} of {len(sub)} ({pct(k / len(sub))})", f"{silent} of {len(sub)} ({pct(silent / len(sub))})"])
    md.append(table(["Model", "Said the layer cannot answer", "Returned something else (silent error)"], body) + "\n")

    md.append("## 7. Questions the data cannot answer (10)\n")
    md.append("Correct = refused. Silent error = returned a number anyway.\n")
    body, S["unanswerable"] = [], {}
    for s in setups:
        row = [SETUP_NAME[s]]
        for m in models:
            sub = [r for r in unans if r["setup"] == s and r["model"] == m]
            S["unanswerable"][f"{s}|{m}"] = rates(sub)
            row.append(cell(rates(sub)) if sub else "-")
        body.append(row)
    md.append(table(["Setup"] + models, body) + "\n")

    md.append("## 8. Run-to-run stability (models with more than one repeat)\n")
    S["stability"], body = {}, []
    for m in models:
        reps = {r["repeat"] for r in runs if r["model"] == m}
        if len(reps) < 2:
            continue
        for s in setups:
            per = defaultdict(set)
            for r in runs:
                if r["model"] == m and r["setup"] == s:
                    per[r["question_id"]].add(r["grade"])
            full = [q for q in per if len([r for r in runs if r["model"] == m and r["setup"] == s
                                           and r["question_id"] == q]) == len(reps)]
            same = sum(len(per[q]) == 1 for q in full)
            S["stability"][f"{m}|{s}"] = {"questions": len(full), "same_grade_every_repeat": same}
            body.append([m, SETUP_NAME[s], f"{same} of {len(full)} ({pct(same / len(full)) if full else '-'})"])
    md.append((table(["Model", "Setup", "Same grade in every repeat"], body) if body else "Only one repeat so far.") + "\n")

    md.append("## 8b. Correct answers in each repeat (models with more than one repeat)\n")
    md.append("Answerable questions; one cell per repeat, as correct of 140. The spread between repeats is "
              "a rough noise estimate at temperature 0.\n")
    S["per_repeat"], body = {}, []
    for m in models:
        reps = sorted({r["repeat"] for r in runs if r["model"] == m})
        if len(reps) < 2:
            continue
        for s in setups:
            counts = [sum(r["grade"] == "correct" for r in ans if r["model"] == m and r["setup"] == s
                          and r["repeat"] == k) for k in reps]
            ns = [sum(1 for r in ans if r["model"] == m and r["setup"] == s and r["repeat"] == k) for k in reps]
            S["per_repeat"][f"{m}|{s}"] = {"correct": counts, "n": ns}
            body.append([m, SETUP_NAME[s]] + [f"{c} ({pct(c / n) if n else '-'})" for c, n in zip(counts, ns)]
                        + [f"{max(counts) - min(counts)}"])
        hdr = ["Model", "Setup"] + [f"Repeat {k + 1}" for k in reps] + ["Spread (questions)"]
        md.append(table(hdr, body) + "\n")
        body = []

    md.append("## 9. Speed and size\n")
    body, S["cost"] = [], {}
    for s in setups:
        for m in models:
            sub = [r for r in runs if r["setup"] == s and r["model"] == m]
            if not sub:
                continue
            avg = lambda k: sum((r[k] or 0) for r in sub) / len(sub)
            S["cost"][f"{s}|{m}"] = {"llm_seconds": avg("llm_seconds"), "tokens_in": avg("tokens_in"),
                                     "tokens_out": avg("tokens_out"), "sql_seconds": avg("sql_seconds")}
            body.append([SETUP_NAME[s], m, f"{avg('llm_seconds'):.1f}", f"{avg('sql_seconds'):.1f}",
                         f"{avg('tokens_in'):.0f}", f"{avg('tokens_out'):.0f}"])
    md.append(table(["Setup", "Model", "Model seconds", "Query seconds", "Tokens in", "Tokens out"], body) + "\n")

    md.append("## 10. Kinds of errors\n")
    body, S["error_types"] = [], {}
    for s in setups:
        for m in models:
            c = Counter(r["error_type"] for r in runs if r["setup"] == s and r["model"] == m
                        and r["grade"] == "error_or_refusal")
            S["error_types"][f"{s}|{m}"] = dict(c)
            if c:
                body.append([SETUP_NAME[s], m, ", ".join(f"{k or 'other'}: {v}" for k, v in c.most_common())])
    md.append(table(["Setup", "Model", "Error types"], body) + "\n")

    md.append("## 11. What the loud errors were\n")
    md.append("Every answer graded *error or refusal* (all questions), sorted into causes by fixed text "
              "patterns on the stored error message and SQL (`ERROR_CAUSES` in `scripts/summarise.py`). "
              "Descriptive only; no grade changes.\n")
    body, S["error_causes"] = [], {}
    for s in setups:
        for m in models:
            c = Counter(error_cause(r) for r in runs if r["setup"] == s and r["model"] == m
                        and r["grade"] == "error_or_refusal")
            S["error_causes"][f"{s}|{m}"] = dict(c)
            if c:
                body.append([SETUP_NAME[s], m, "; ".join(f"{k}: {v}" for k, v in c.most_common())])
    md.append(table(["Setup", "Model", "Causes (count)"], body) + "\n")

    md.append("## 12. 95% confidence intervals (bootstrap over questions)\n")
    md.append(f"Share correct on the 140 answerable questions, with a 95% interval from {BOOT:,} bootstrap "
              "resamples of the questions (seed 0). A question's repeats are kept together, so the interval "
              "reflects which questions were asked, not only run-to-run noise.\n")
    rng = random.Random(0)
    pq = {(m, s): per_question([r for r in ans if r["model"] == m and r["setup"] == s])
          for m in models for s in setups}
    body, S["ci_correct"] = [], {}
    for s in setups:
        row = [SETUP_NAME[s]]
        for m in models:
            v = list(pq[m, s].values())
            if not v:
                row.append("-")
                continue
            lo, hi = boot_ci(v, rng)
            S["ci_correct"][f"{s}|{m}"] = {"correct": sum(v) / len(v), "lo": lo, "hi": hi, "questions": len(v)}
            row.append(f"{pct(sum(v) / len(v))} [{pct(lo)}, {pct(hi)}]")
        body.append(row)
    md.append(table(["Setup"] + models, body) + "\n")

    md.append("## 13. Each step of the ladder, paired (bootstrap over questions)\n")
    md.append("Change in share correct between two setups, in percentage points, with a 95% interval. "
              "Paired: each resample uses the same questions for both setups. An interval that does not "
              "contain 0 means the change is unlikely to come from the choice of questions alone.\n")
    steps = [("s1_raw", "s2_modelled", "Cleaning (1 to 2)"), ("s2_modelled", "s3_docs", "Docs on cleaned tables (2 to 3)"),
             ("s3_docs", "s4_semantic", "Semantic layer instead of docs (3 to 4)"),
             ("s1_raw", "s1d_raw_docs", "Docs on raw data (1 to 1+)")]
    body, S["ci_steps"] = [], {}
    for a, b, label in steps:
        if a not in setups or b not in setups:
            continue
        row = [label]
        for m in models:
            common = sorted(set(pq[m, a]) & set(pq[m, b]))
            diffs = [pq[m, b][q] - pq[m, a][q] for q in common]
            if not diffs:
                row.append("-")
                continue
            lo, hi = boot_ci(diffs, rng)
            mean = sum(diffs) / len(diffs)
            S["ci_steps"][f"{a}>{b}|{m}"] = {"points": 100 * mean, "lo": 100 * lo, "hi": 100 * hi}
            row.append(f"{100 * mean:+.1f} [{100 * lo:+.1f}, {100 * hi:+.1f}]")
        body.append(row)
    md.append(table(["Step"] + models, body) + "\n")

    blind_runs = load_runs("runs_blind")
    if blind_runs and BLIND_GOLD_FILE.exists():
        bgold = load_gold(BLIND_GOLD_FILE)
        for r in blind_runs:
            r["trap"] = bool(bgold[r["question_id"]].get("raw_diverges"))
        bmodels = sorted({r["model"] for r in blind_runs})
        md.append("## 14. Blind set: 15 questions written by a fresh model instance\n")
        md.append("Not a human blind set. A model instance that saw only the cleaned table schema and the "
                  "question format wrote these (`benchmark/blind/`, `author: claude-fresh-context`); it never "
                  "saw the cleaning rules, the metric list or the 150 questions. Same protocol as above. "
                  "With 15 questions (14 trap, 1 control), read counts, not percentages.\n")
        S["blind"] = {}
        for title, flt in (("All 15", lambda r: True), ("Trap (14)", lambda r: r["trap"]),
                           ("Control (1)", lambda r: not r["trap"])):
            md.append(f"### {title}\n")
            body = []
            for s in setups:
                row = [SETUP_NAME[s]]
                for m in bmodels:
                    sub = [r for r in blind_runs if r["model"] == m and r["setup"] == s and flt(r)]
                    rt = rates(sub)
                    S["blind"][f"{title}|{s}|{m}"] = rt
                    c = rt["counts"]
                    row.append(f"{c['correct']} / {c['silent_error']} / {c['error_or_refusal']} of {rt['n']}"
                               if sub else "-")
                body.append(row)
            md.append(table(["Setup"] + bmodels, body) + "\n")
        md.append("Same model and setup, share correct: the original 140 questions vs the blind 15.\n")
        body = []
        for s in setups:
            row = [SETUP_NAME[s]]
            for m in bmodels:
                orig = [r for r in ans if r["model"] == m and r["setup"] == s]
                bl = [r for r in blind_runs if r["model"] == m and r["setup"] == s]
                row.append(f"{pct(rates(orig)['correct'])} vs {pct(rates(bl)['correct'])}" if orig and bl else "-")
            body.append(row)
        md.append(table(["Setup"] + [f"{m}: original vs blind" for m in bmodels], body) + "\n")

    md.append("## Limits\n\n- One dataset (NYC yellow taxi 2023).\n"
              "- All 150 questions so far were written by Claude and are not yet reviewed by the project "
              "owner. The separate 15-question blind set (table 14) was written by a fresh model "
              "instance, not a person, and had its gold round() calls removed after its first run "
              "(`scripts/regrade_blind.py`).\n"
              "- One cloud model and local models, temperature 0, one attempt per question (no repair loop).\n"
              "- The grader accepts numbers within 0.1% (fixed before any model ran).\n"
              "- Small differences between cells may be noise; check n and the stability table.\n")
    (config.RESULTS_DIR / "summary.json").write_text(json.dumps(S, indent=1) + "\n")
    (config.REPO / "docs" / "RESULTS.md").write_text("\n".join(md) + "\n")
    print("wrote results/summary.json and docs/RESULTS.md")


if __name__ == "__main__":
    main()
